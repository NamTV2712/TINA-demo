import assert from 'node:assert/strict';
import {silenceCut} from './silence-cut.js';
const sr=16000;
const audio=new Float32Array(sr*8).fill(.01);
assert.equal(silenceCut(audio),null,'continuous speech stays unconfirmed');
audio.fill(0,sr*5,sr*5.6);
const cut=silenceCut(audio)!;
assert(cut>=sr*5.2 && cut<=sr*5.4,'cut lies inside the long quiet gap');
const left=audio.slice(0,cut),right=audio.slice(cut);
assert.deepEqual(Float32Array.from([...left,...right]),audio,'no boundary audio is dropped or duplicated');
const quiet=new Float32Array(sr*8).fill(.0012);
assert.equal(silenceCut(quiet),null,'quiet speech is not classified as silence');
audio.fill(.01);audio.fill(0,sr*5,sr*5.1);
assert.equal(silenceCut(audio),null,'a 100ms consonant gap cannot close a window');
audio.fill(.01);audio.fill(0,sr,sr*1.6);
assert.equal(silenceCut(audio),null,'an old pause cannot truncate recent context');
assert.throws(()=>silenceCut(audio,0),RangeError);
audio.fill(.01);audio.fill(0,sr*5,sr*5.6);
assert.equal(silenceCut(audio,sr,sr*6),null,'a pause before the target cannot reduce the requested context');
assert.throws(()=>silenceCut(audio,sr,-1),RangeError);
console.log('silence-cut: boundary/retention checks passed');
