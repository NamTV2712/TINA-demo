import assert from 'node:assert/strict';
import { PcmReplayBuffer } from './pcm-replay';

const queue = new PcmReplayBuffer();
const frame = (source: number, startSample: number, count = 16000) => ({source,startSample,endSample:startSample+count,wire:new ArrayBuffer(20+count*4)});
const first = frame(0,0);
queue.enqueue(first); queue.enqueue(frame(0,32000)); queue.enqueue(frame(1,0));
assert.equal(queue.acknowledge(0,0,16000),false,'unsent PCM cannot be acknowledged');
assert.equal(queue.enqueue(first),false);
assert.equal(queue.acknowledge(0,0,48000),false,'ACK only covers the exact sent range, never a gap');
assert.equal(queue.acknowledge(2,0,16000),false);
const sent: ArrayBuffer[] = [];
queue.flush(wire=>sent.push(wire),()=>sent.length<1); assert.equal(sent.length,1);
queue.flush(wire=>sent.push(wire),()=>true); assert.equal(sent.length,3);
queue.flush(wire=>sent.push(wire),()=>true); assert.equal(sent.length,3,'no duplicate send on the same socket');
assert.equal(queue.acknowledge(0,0,16000),true);
queue.replay(); queue.flush(wire=>sent.push(wire),()=>true);
assert.equal(sent.length,5); assert.equal(queue.size,2);
assert.equal(queue.bytes,2*first.wire.byteLength);
const changed=frame(0,32000);new Uint8Array(changed.wire)[20]=1;
assert.throws(()=>queue.enqueue(changed),/changed/);
const sourceCap=new PcmReplayBuffer();sourceCap.enqueue(frame(0,0,16000*30));
assert.throws(()=>sourceCap.enqueue(frame(0,16000*30,1)),/source 0 range/);
sourceCap.enqueue(frame(1,0,1));
const bytesCap=new PcmReplayBuffer();
for(let i=0;i<4;i++)bytesCap.enqueue(frame(i,0,16000*30));
assert.throws(()=>bytesCap.enqueue(frame(4,0,16000*30)),/buffer full/);
const countCap=new PcmReplayBuffer();
for(let i=0;i<2048;i++)countCap.enqueue(frame(0,i,1));
assert.throws(()=>countCap.enqueue(frame(0,2048,1)),/buffer full/);
assert.throws(()=>queue.enqueue(frame(0,-1)),/Invalid/);
console.log('PASS PCM replay: exact range ACK, immutable paced replay, source isolation and byte/sample/frame caps');
